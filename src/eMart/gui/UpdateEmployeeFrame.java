    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if(!validateInput()){
            JOptionPane.showMessageDialog(null, "Please Fill All Fields","Incomplete Data",JOptionPane.ERROR_MESSAGE);
            return;
        }
        try{
            EmployeePojo empp=new EmployeePojo();
            empp.setEmpId(jrEmpId.getSelectedItem().toString());
            empp.setEmpName(txtEmpName.getText());
            empp.setJob(jrEmpJob.getSelectedItem().toString());
            empp.setSalary(Double.parseDouble(txtEmpSal.getText()));
            boolean result=EmployeesDAO.UpdateEmployee(empp);
            if(!result)
            {
                JOptionPane.showMessageDialog(null, "Record Not Updated","Error",JOptionPane.ERROR_MESSAGE);
                return;
            }
            JOptionPane.showMessageDialog(null, "Record Updated Successfully","Success",JOptionPane.INFORMATION_MESSAGE);
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(null, "Database Error","Error!!",JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
        catch(NumberFormatException e){
            JOptionPane.showMessageDialog(null, "Please Input Numeric value for Salary","Error!!",JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

