    private void LoadDetails(){
        try{
            String str=jrEmpId.getSelectedItem().toString();
            EmployeePojo em=EmployeesDAO.getDetails(str);
            txtEmpName.setText(em.getEmpName());
            jrEmpJob.setSelectedItem(em.getJob());
            txtEmpSal.setText(Double.toString(em.getSalary()));
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(null, "Database Error","Error!!",JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }
    private void LoadEmpId(){
        try{
            jrEmpId.removeAllItems();
            List<String> l=EmployeesDAO.getIds();
            for(String str:l)
            {
                jrEmpId.addItem(str);
            }
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(null, "Database Error","Error!!",JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

