    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String userId=jrRecepId.getSelectedItem().toString();
        try{
            boolean res=ReceptionistDAO.DeleteRecep(userId);
            if(res)
            {
               JOptionPane.showMessageDialog(null, "Receptionist Deleted Successfully","Successfully",JOptionPane.INFORMATION_MESSAGE);
               jrRecepId.removeItemAt(jrRecepId.getSelectedIndex());
               if(jrRecepId.getItemCount()==0)
                   btnDelete.setEnabled(false);
               return;
            }else{
               JOptionPane.showMessageDialog(null, "Receptionist is Not Deleted","Try Again",JOptionPane.ERROR_MESSAGE);
            }
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(null, "Database Error","Error!!",JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

