    private void loadRecepId(){
        try{
            List<String> recepl=ReceptionistDAO.getRecepId();
            if(recepl.isEmpty())
            {
                JOptionPane.showMessageDialog(null, "No Receptionist is Present", "Information",JOptionPane.INFORMATION_MESSAGE);
                return;
            }
            for(String id:recepl)
            {
                jrRecepId.addItem(id);
            }
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(null, "Database Error","Error!!",JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

