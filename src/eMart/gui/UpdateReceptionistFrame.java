    private void loadRecep(){
        try{
            recep=ReceptionistDAO.getAllRecepId();
            if(recep.isEmpty())
            {
                JOptionPane.showMessageDialog(null, "No Receptionist Present","Error",JOptionPane.INFORMATION_MESSAGE);
                return;
            }
            Set<String> keys=recep.keySet();
            for(String id:keys)
            {
                jrEmpId.addItem(id);
            }
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(null, "Database Error","Error!!",JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }
    private boolean ValidateInputs(){
        char[] cpwd=txtPassword.getPassword();
        char[] cpwd2=txtRePassword.getPassword();
        if(cpwd.length<4 ||cpwd2.length<4)
        {
            JOptionPane.showMessageDialog(null, "Password must be 4 character long","Error!!",JOptionPane.ERROR_MESSAGE);
            return false;
        }
        pwd=String.valueOf(cpwd);
        String pwd2=String.valueOf(cpwd2);
        if(!pwd.equals(pwd2))
        {
            JOptionPane.showMessageDialog(null, "Password do not match","Error!!",JOptionPane.ERROR_MESSAGE);
            return false;
        }
        return true;
    }
