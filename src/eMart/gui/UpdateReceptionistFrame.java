    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if(!ValidateInputs())
                return;
        try{
            String userId=jrEmpId.getSelectedItem().toString();
            boolean res=ReceptionistDAO.updatePassword(userId, pwd);
            if(res){
                JOptionPane.showMessageDialog(null, "Password Changed Successfully","Successfull",JOptionPane.INFORMATION_MESSAGE);
                clearTxt();
                jrEmpId.setSelectedIndex(0);
                return;
              }
              else{
               JOptionPane.showMessageDialog(null, "Password not Changed","Error!!",JOptionPane.ERROR_MESSAGE);
               return;
              }
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(null, "Database Error","Error!!",JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void clearTxt(){
        txtPassword.setText("");
        txtRePassword.setText("");
    }
