    private void loadProductDetails(){
        try{
            List<ProductPojo> l=ProductDAO.getProductDetails();
            if(l.isEmpty())
            {
                JOptionPane.showMessageDialog(null, "No Products Present in Stock","Error!!",JOptionPane.ERROR_MESSAGE);
                return;
            }
            Object[] row=new Object[7];
            tm=(DefaultTableModel)jtViewStock.getModel();
            for(ProductPojo p:l)
            {
                row[0]=p.getPId();
                row[1]=p.getpName();
                row[2]=p.getpCompany();
                row[3]=p.getpPrice();
                row[4]=p.getOurPrice();
                row[5]=p.getQuantity();
                row[6]=p.getTax()+"%";
                tm.addRow(row);
            }
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(null, "Database Error","Error!!",JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

