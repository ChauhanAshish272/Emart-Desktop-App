    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        try{
            int r=jtViewStock.getSelectedRow();
            if(r==-1)
            {
                JOptionPane.showMessageDialog(null, "Please Select a Row First","Error!!",JOptionPane.ERROR_MESSAGE);
                return;
            }
            String pId=jtViewStock.getValueAt(r,0).toString();
            boolean res=ProductDAO.deleteProduct(pId);
            if(res){
                JOptionPane.showMessageDialog(null, "Product Deleted Successfully","Error!!",JOptionPane.INFORMATION_MESSAGE);
                tm.setRowCount(0);
                loadProductDetails();
                return;
            }
            JOptionPane.showMessageDialog(null, "Product Not Deleted","Error!!",JOptionPane.ERROR_MESSAGE);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Database Error","Error!!",JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

